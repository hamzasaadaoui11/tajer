/**
 * Format Moroccan Currency according to Moroccan commercial standards
 * e.g. 1 250,00 DH or 1 250,00 د.م.
 */
export function formatMAD(amount: number, lang: Language = 'ar'): string {
  const formatted = (amount || 0).toLocaleString('fr-FR', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  if (lang === 'ar') {
    return `${formatted} د.م.`;
  }
  return `${formatted} DH`;
}

/**
 * Format Product Unit of measurement according to selected language
 */
export function formatUnit(unit: string, lang: Language = 'ar'): string {
  if (!unit) return '';
  if (lang === 'ar') return unit;
  const map: Record<string, string> = {
    'علبة': 'boîte',
    'قنينة': 'bouteille',
    'باكي': 'paquet',
    'حبة': 'pièce',
    'قطعة': 'pièce',
    'كيلو': 'kg',
    'كغ': 'kg',
    'غرام': 'g',
    'لتر': 'L',
    'متر': 'm',
    'كرتونة': 'carton',
    'طرد': 'colis',
  };
  return map[unit] || unit;
}

export function formatMoroccanPhone(phone: string): string {
  const clean = phone.replace(/\D/g, '');
  if (clean.length === 10) {
    return `${clean.slice(0, 2)} ${clean.slice(2, 4)} ${clean.slice(4, 6)} ${clean.slice(6, 8)} ${clean.slice(8, 10)}`;
  }
  return phone;
}
